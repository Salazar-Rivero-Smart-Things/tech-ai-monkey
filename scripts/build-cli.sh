#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Tech AI monkey — build the standalone CLI:
#
#   * Linux   -> web/public/downloads/tech-ai_<version>_amd64.deb
#   * Windows -> web/public/downloads/tech-ai_<version>_windows_x64.exe
#   * checksums.txt with SHA-256 for both
#
# Binaries are compiled with Bun (single-file executables). If Bun is not
# available we fall back to a Node-based .deb (the target machine then needs
# Node.js 18+ and no .exe is produced).
#
# Run:
#     bash scripts/build-cli.sh                  # Linux + Windows
#     bash scripts/build-cli.sh --linux-only     # skip the Windows build
#
# It also produces, when the tools are available:
#   * cli/assets/icon.*                  generated by scripts/make-icons.py
#   * tech-ai_<v>_windows_x64_setup.exe  NSIS installer: Start-menu entry with
#     the app icon, optional desktop shortcut, PATH entry and an uninstaller
#     that also cleans PATH up again (needs makensis).
#
# The Windows installer is cross-built natively on Linux by makensis; nothing
# is emulated. Because bun can only attach an icon to a .exe when bun itself
# runs on Windows, the icon for the shortcuts comes from the installer.
#
# The script verifies what it produces before declaring success: the Linux
# binary is executed, the .deb is read back, and the .exe is checked to be a
# real 64-bit PE. The glibc requirement written into the .deb is measured from
# the binary's own symbols instead of guessed, so the package is not refused by
# dpkg on older-but-capable distributions.
#
# The resulting files are git-ignored (they are large); the /download page on
# the website lists whatever is present in web/public/downloads/.
#
# macOS is NOT built here: the binary can be cross-compiled with
# --target=bun-darwin-arm64 / bun-darwin-x64, but it must be code-signed and
# notarised on a Mac. See docs/macos-bygg-cli.txt.
# ---------------------------------------------------------------------------
set -euo pipefail

REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
CLI_DIR="$REPO_DIR/cli"
OUT_DIR="$REPO_DIR/web/public/downloads"
VERSION="$(node -p "require('$CLI_DIR/package.json').version" 2>/dev/null || echo 1.0.0)"
PKG="tech-ai"
STAGE="$REPO_DIR/.build/cli"
ASSETS_DIR="$CLI_DIR/assets"
ICON_ICO="$ASSETS_DIR/icon.ico"

log() { printf '\033[1m▸\033[0m %s\n' "$*"; }
die() { printf '\033[31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

LINUX_ONLY=0
for arg in "$@"; do
  case "$arg" in
    --linux-only|--no-windows) LINUX_ONLY=1 ;;
    -h|--help)
      echo "Bruk: bash scripts/build-cli.sh [--linux-only]"
      echo "  Bygger .deb (Linux) og .exe (Windows) til web/public/downloads/"
      exit 0
      ;;
    *) die "Ukjent flagg: $arg" ;;
  esac
done

[ -f "$CLI_DIR/src/index.js" ] || die "Fant ikke cli/src/index.js"
command -v dpkg-deb >/dev/null 2>&1 || die "dpkg-deb mangler (installer dpkg-dev)"

echo "tech-ai CLI $VERSION -> $OUT_DIR"

rm -rf "$STAGE"
mkdir -p "$STAGE" "$OUT_DIR"

# --- 0. icons ----------------------------------------------------------------
if [ ! -f "$ICON_ICO" ] && command -v python3 >/dev/null 2>&1; then
  log "Genererer ikoner (scripts/make-icons.py)"
  python3 "$REPO_DIR/scripts/make-icons.py" >/dev/null || log "ADVARSEL: ikon-generering feilet"
fi
if [ -f "$ICON_ICO" ]; then
  log "Ikon: $ICON_ICO"
else
  log "ADVARSEL: $ICON_ICO mangler — .exe-en får ikke eget ikon og menyoppføringen blir enklere"
fi

# --- 1. locate a compiler -----------------------------------------------------
BUN=""
if command -v bun >/dev/null 2>&1; then
  BUN="bun"
elif command -v npx >/dev/null 2>&1; then
  log "bun er ikke installert – provde a hente det via npx (kan ta litt tid)"
  if npx --yes bun@1 --version >/dev/null 2>&1; then
    BUN="npx --yes bun@1"
  fi
fi

compile_binary() { # <target> <outfile> [ekstra bun-flagg...]
  local target="$1" outfile="$2"
  shift 2
  # shellcheck disable=SC2086
  $BUN build "$CLI_DIR/src/index.js" --compile --minify \
    --target="$target" --outfile="$outfile" "$@"
}

# --- 2. compile ---------------------------------------------------------------
LINUX_BIN="$STAGE/tech-ai"
WINDOWS_BIN=""
HAVE_BUN=0

if [ -n "$BUN" ]; then
  log "Kompilerer Linux-binær (bun-linux-x64)"
  if compile_binary bun-linux-x64 "$LINUX_BIN"; then
    HAVE_BUN=1
  else
    log "Kompilering feilet – gar over til Node-varianten"
  fi

  if [ "$HAVE_BUN" = "1" ] && [ "$LINUX_ONLY" = "0" ]; then
    log "Kompilerer Windows-binær (bun-windows-x64)"
    WINDOWS_BIN="$STAGE/tech-ai.exe"
    # bun only accepts --windows-icon/-title/-version/-publisher/... when bun
    # itself runs on Windows. Cross-compiling from Linux therefore produces a
    # plain .exe, and the NSIS installer supplies the icon for the Start-menu
    # and desktop shortcuts (and for "Apps & features") instead.
    WIN_ARGS=()
    case "$(uname -s 2>/dev/null)" in
      MINGW*|MSYS*|CYGWIN*)
        WIN_ARGS=(
          "--windows-title=Tech AI monkey"
          "--windows-description=Command-line client for the Tech AI monkey agent"
          "--windows-publisher=Salazar Rivero Smart Things"
          "--windows-version=${VERSION}.0"
          "--windows-copyright=Salazar Rivero Smart Things"
        )
        [ -f "$ICON_ICO" ] && WIN_ARGS+=("--windows-icon=$ICON_ICO")
        ;;
    esac
    compile_binary bun-windows-x64 "$WINDOWS_BIN" "${WIN_ARGS[@]}" || {
      WINDOWS_BIN=""
      log "Windows-bygget feilet – hopper over .exe"
    }
  fi
else
  log "bun er utilgjengelig – lager en Node-basert .deb i stedet"
fi

if [ "$HAVE_BUN" = "0" ]; then
  cat > "$LINUX_BIN" <<EOF
#!/usr/bin/env node
// Tech AI monkey CLI $VERSION — Node launcher.
// The real implementation is installed under /usr/share/tech-ai-cli.
import("/usr/share/tech-ai-cli/index.js");
EOF
  chmod +x "$LINUX_BIN"
fi

# --- 3. build the .deb --------------------------------------------------------
DEB_ROOT="$STAGE/deb"
mkdir -p "$DEB_ROOT/DEBIAN" "$DEB_ROOT/usr/bin" "$DEB_ROOT/usr/share/doc/$PKG"

log "Setter opp .deb-struktur"
install -m 0755 "$LINUX_BIN" "$DEB_ROOT/usr/bin/tech-ai"

# Menu launcher. Two jobs: pick whichever build we actually installed, and keep
# the terminal window open when the program exits with an error so a desktop
# user can read the message instead of watching it flash past.
cat > "$DEB_ROOT/usr/bin/$PKG-terminal" <<'EOF'
#!/bin/sh
# Tech AI monkey — application-menu launcher (installed by the .deb).
# You do not need this in a terminal; use "tech-ai" directly there.
#
# Why this exists: a desktop launcher gets no interactive terminal that can
# answer "Sign in now? [Y/n]", so the first run signs the user in through the
# browser itself and only then starts the chat. It also keeps the window open
# on error, so the message can actually be read instead of flashing past.

TECH_AI=""
if [ -x /usr/bin/tech-ai ]; then
  TECH_AI=/usr/bin/tech-ai
elif [ -x /usr/local/bin/tech-ai ]; then
  TECH_AI=/usr/local/bin/tech-ai
fi

run_cli() {
  if [ -n "$TECH_AI" ]; then
    "$TECH_AI" "$@"
  elif [ -f /usr/share/tech-ai-cli/index.js ]; then
    if command -v node >/dev/null 2>&1; then
      node /usr/share/tech-ai-cli/index.js "$@"
    else
      printf 'Node.js mangler. Installer nodejs (>= 18) og prov igjen.\n' >&2
      return 127
    fi
  else
    printf 'tech-ai er ikke installert. Installer .deb-pakken pa nytt.\n' >&2
    return 127
  fi
}

have_credentials() {
  _dir="${TECH_AI_CONFIG_DIR:-$HOME/.config/tech-ai}"
  [ -f "$_dir/credentials.json" ]
}

status=0
if [ "$#" -eq 0 ] && ! have_credentials; then
  printf '\nForste gang: du ma logge inn for a bruke Tech AI monkey.\n'
  printf 'Nettleseren din apnes — logg inn med Google eller e-post.\n\n'
  if run_cli login; then
    printf '\n'
    run_cli chat || status=$?
  else
    status=$?
    printf '\nInnloggingen ble ikke fullfort.\n' >&2
  fi
else
  run_cli "$@" || status=$?
fi

if [ -t 0 ]; then
  printf '\nTrykk Enter for a lukke dette vinduet... '
  read -r _ || true
fi

exit $status
EOF
chmod 0755 "$DEB_ROOT/usr/bin/$PKG-terminal"
if [ "$HAVE_BUN" = "0" ]; then
  mkdir -p "$DEB_ROOT/usr/share/tech-ai-cli"
  cp -r "$CLI_DIR/src/." "$DEB_ROOT/usr/share/tech-ai-cli/"
  DEPENDS="nodejs (>= 18)"
else
  # Declare the glibc version the binary ACTUALLY needs, measured from its own
  # symbols. Over-declaring makes dpkg refuse the package on older distributions
  # that would run it perfectly well.
  GLIBC_MIN="2.17"
  if command -v objdump >/dev/null 2>&1; then
    MEASURED="$(objdump -T "$LINUX_BIN" 2>/dev/null \
      | grep -oE 'GLIBC_[0-9]+\.[0-9]+' | sed 's/^GLIBC_//' | sort -uV | tail -n1 || true)"
    [ -n "$MEASURED" ] && GLIBC_MIN="$MEASURED"
  else
    log "objdump mangler — bruker konservativ libc6 (>= $GLIBC_MIN)"
  fi
  log "Linux-binæren krever libc6 (>= $GLIBC_MIN)"
  DEPENDS="libc6 (>= $GLIBC_MIN)"
fi

INSTALLED_SIZE="$(du -sk "$DEB_ROOT/usr" | cut -f1)"

cat > "$DEB_ROOT/DEBIAN/control" <<EOF
Package: $PKG
Version: $VERSION
Section: utils
Priority: optional
Architecture: amd64
Depends: $DEPENDS
Recommends: desktop-file-utils
Installed-Size: $INSTALLED_SIZE
Maintainer: Salazar Rivero Smart Things <support@tech-ai.tech>
Homepage: https://tech-ai.tech
Description: Command-line client for Tech AI monkey
 Ask the Tech AI monkey agent from your terminal. Sign in with Google,
 e-mail/password or an API key, then use "tech-ai ask" or "tech-ai chat".
EOF

cat > "$DEB_ROOT/usr/share/doc/$PKG/README.md" <<EOF
# Tech AI monkey CLI

Install:  sudo dpkg -i ${PKG}_${VERSION}_amd64.deb
Sign in:  tech-ai login
Ask:      tech-ai ask "hello"
Chat:     tech-ai chat

Open a terminal and run "tech-ai". On the first run it offers to sign you in
through your browser, then drops you straight into the chat.

On a desktop Linux the application menu also gets a "Tech AI monkey" entry
(right-click for "Sign in"). It opens a terminal and starts the same flow, and
keeps the window open if something goes wrong.

Docs: https://tech-ai.tech/download
EOF

# --- 3a. desktop entry: application-menu icon ---------------------------------
mkdir -p "$DEB_ROOT/usr/share/applications" \
         "$DEB_ROOT/usr/share/icons/hicolor/scalable/apps"

cat > "$DEB_ROOT/usr/share/applications/$PKG.desktop" <<'EOF'
[Desktop Entry]
Type=Application
Version=1.0
Name=Tech AI monkey
GenericName=AI assistant
Comment=Ask the Tech AI monkey agent — signs you in on the first run
Exec=tech-ai-terminal
Icon=tech-ai
Terminal=true
Categories=Utility;
Keywords=ai;assistant;agent;chat;tech-ai;
StartupNotify=false
Actions=SignIn;

[Desktop Action SignIn]
Name=Sign in to Tech AI monkey
Exec=tech-ai-terminal login
EOF

# Same design as the .exe/.app icons — cli/assets/icon.svg is the source of truth.
if [ -f "$ASSETS_DIR/icon.svg" ]; then
  install -m 0644 "$ASSETS_DIR/icon.svg" "$DEB_ROOT/usr/share/icons/hicolor/scalable/apps/$PKG.svg"
else
  log "ADVARSEL: $ASSETS_DIR/icon.svg mangler — bruker et enklere ikon"
  printf '%s\n' \
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">' \
    '  <rect width="1024" height="1024" rx="224" fill="#0b0b0c"/>' \
    '  <circle cx="512" cy="528" r="288" fill="none" stroke="#34d399" stroke-width="64"/>' \
    '</svg>' \
    > "$DEB_ROOT/usr/share/icons/hicolor/scalable/apps/$PKG.svg"
fi

# Refresh the menu and icon caches on install/removal, but only where the tools exist.
cat > "$DEB_ROOT/DEBIAN/postinst" <<'EOF'
#!/bin/sh
set -e
if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database -q /usr/share/applications || true
fi
if command -v gtk-update-icon-cache >/dev/null 2>&1; then
  gtk-update-icon-cache -q -t -f /usr/share/icons/hicolor || true
fi
exit 0
EOF

cat > "$DEB_ROOT/DEBIAN/postrm" <<'EOF'
#!/bin/sh
set -e
if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database -q /usr/share/applications || true
fi
exit 0
EOF

chmod 0755 "$DEB_ROOT/DEBIAN/postinst" "$DEB_ROOT/DEBIAN/postrm"

DEB_FILE="$OUT_DIR/${PKG}_${VERSION}_amd64.deb"
log "Bygger $DEB_FILE"
dpkg-deb --build --root-owner-group "$DEB_ROOT" "$DEB_FILE" >/dev/null

# --- 3b. verify what we just built --------------------------------------------
if dpkg-deb -f "$DEB_FILE" >/dev/null 2>&1; then
  log "✓ .deb er gyldig — $(dpkg-deb -f "$DEB_FILE" Depends)"
else
  die ".deb-pakken kunne ikke leses tilbake. Bygget er ugyldig."
fi

if [ "$HAVE_BUN" = "1" ]; then
  if RUNS="$("$LINUX_BIN" --version 2>&1 | head -n1)" && [ -n "$RUNS" ]; then
    log "✓ Linux-binæren kjører: $RUNS"
  else
    die "Linux-binæren ble bygget, men kjører ikke. Avbryter før noe publiseres."
  fi
fi

# --- 4. Windows binary --------------------------------------------------------
EXE_FILE="$OUT_DIR/${PKG}_${VERSION}_windows_x64.exe"
if [ "$LINUX_ONLY" = "1" ]; then
  rm -f "$EXE_FILE"
  log "Hoppet over Windows — ba om --linux-only (.exe fjernet fra nedlastingene)"
elif [ -n "$WINDOWS_BIN" ] && [ -f "$WINDOWS_BIN" ]; then
  cp -f "$WINDOWS_BIN" "$EXE_FILE"
  if command -v file >/dev/null 2>&1; then
    if file "$EXE_FILE" | grep -q 'PE32+'; then
      log "✓ Windows-binæren er en gyldig 64-bit .exe"
    else
      rm -f "$EXE_FILE"
      die "Windows-binæren er ikke en gyldig 64-bit PE — fjernet, ikke publisert."
    fi
  else
    log "Kopierte $EXE_FILE"
  fi
else
  rm -f "$EXE_FILE"
  log "ADVARSEL: ingen .exe ble laget."
  log "          Windows-knappen på /download vil forsvinne. Kjør på nytt med"
  log "          bun tilgjengelig for å få den med igjen."
fi

# --- 4b. Windows installer (Start-meny, ikon, avinstallering) ------------------
# makensis cross-bygger denne natively på Linux — ingen emulering.
SETUP_FILE="$OUT_DIR/${PKG}_${VERSION}_windows_x64_setup.exe"
if [ "$LINUX_ONLY" = "1" ] || [ ! -f "$EXE_FILE" ]; then
  rm -f "$SETUP_FILE"
elif command -v makensis >/dev/null 2>&1; then
  log "Bygger Windows-installer (NSIS)"
  ICON_DEFINE=()
  [ -f "$ICON_ICO" ] && ICON_DEFINE=("-DSOURCE_ICON=$ICON_ICO")
  if makensis -V2 \
       -DAPP_VERSION="$VERSION" \
       -DSOURCE_EXE="$EXE_FILE" \
       -DOUTFILE="$SETUP_FILE" \
       ${ICON_DEFINE[@]+"${ICON_DEFINE[@]}"} \
       "$REPO_DIR/scripts/windows-installer.nsi" >/dev/null 2>&1; then
    if command -v file >/dev/null 2>&1 && file "$SETUP_FILE" | grep -q 'Nullsoft'; then
      log "✓ Windows-installer: Start-meny, ikon og avinstallering"
    else
      log "✓ Windows-installer bygget"
    fi
  else
    rm -f "$SETUP_FILE"
    log "ADVARSEL: NSIS-bygget feilet — den frittstående .exe-en virker fortsatt"
  fi
else
  rm -f "$SETUP_FILE"
  log "makensis mangler — hopper over Windows-installeren (sudo apt install nsis)"
fi

# --- 5. checksums -------------------------------------------------------------
# Portable SHA-256: sha256sum on Linux, shasum on macOS.
hash_file() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{print $1}'
  else
    shasum -a 256 "$1" | awk '{print $1}'
  fi
}

log "Skriver checksums.txt"
(
  cd "$OUT_DIR"
  : > checksums.txt
  for f in $(ls -1 tech-ai_* 2>/dev/null | sort); do
    [ -f "$f" ] || continue
    printf '%s  %s\n' "$(hash_file "$f")" "$f" >> checksums.txt
  done
  cat checksums.txt
)

echo
log "Ferdig. Innhold i web/public/downloads:"
ls -lh "$OUT_DIR" | tail -n +2 | sed 's/^/    /'
echo
log "Neste steg (filen må kopieres til serveren som viser tech-ai.tech, og"
log "tjenesten MÅ restartes — Next.js leser public/ ved oppstart):"
echo "    sudo systemctl restart myai-web"
